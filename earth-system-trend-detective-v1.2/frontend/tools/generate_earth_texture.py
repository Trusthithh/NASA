def xy(pts):
    return [((lo + 180) / 360 * W * SS, (90 - la) / 180 * H * SS) for lo, la in pts]

def mask_from(polys, fill=255):
    img = Image.new("L", (W * SS, H * SS), 0)
    d = ImageDraw.Draw(img)
    for p in polys:
        d.polygon(xy(p), fill=fill)
    return img.resize((W, H), Image.LANCZOS)

def blobs(specs):
    out = np.zeros((H, W), np.float32)
    lon = np.linspace(-180, 180, W)[None, :]
    lat = np.linspace(90, -90, H)[:, None]
    for lo0, lo1, la0, la1, s in specs:
        cx, cy = (lo0 + lo1) / 2, (la0 + la1) / 2
        rx, ry = max((lo1 - lo0) / 2, 1), max((la1 - la0) / 2, 1)
        d = ((lon - cx) / rx) ** 2 + ((lat - cy) / ry) ** 2
        out = np.maximum(out, s * np.clip(1.15 - d, 0, 1))
    return gaussian_filter(out, 6)

def noise(seed, sigma, amp):
    r = np.random.default_rng(seed).standard_normal((H, W)).astype(np.float32)
    r = gaussian_filter(r, sigma)
    return r / (np.abs(r).max() + 1e-6) * amp

def main():
    land = np.asarray(mask_from(LAND.values()), np.float32) / 255
    water = np.asarray(mask_from(WATER.values()), np.float32) / 255
    land = np.clip(land - water, 0, 1)
    land = gaussian_filter(land, 0.8)

    lat = np.linspace(90, -90, H)[:, None] * np.ones((1, W), np.float32)
    ocean_deep = np.array([10, 48, 118], np.float32)
    ocean_shallow = np.array([44, 128, 184], np.float32)
    dist = gaussian_filter(land, 9)
    shelf = np.clip(dist * 2.2, 0, 1)[..., None]
    ocean = ocean_deep + (ocean_shallow - ocean_deep) * shelf
    ocean += noise(3, 18, 6)[..., None]
    ocean *= (1 - 0.18 * (np.abs(lat) / 90) ** 2)[..., None]

    base = np.array([86, 128, 62], np.float32)
    desert = np.array([205, 178, 122], np.float32)
    forest = np.array([30, 88, 40], np.float32)
    taiga = np.array([52, 92, 64], np.float32)
    grass = np.array([140, 150, 72], np.float32)
    rock = np.array([120, 110, 95], np.float32)
    col = np.broadcast_to(base, (H, W, 3)).copy()
    for spec, c in ((GRASS, grass), (FOREST, forest), (TAIGA, taiga), (DESERT, desert)):
        b = np.clip(blobs(spec) + noise(11, 10, 0.18), 0, 1)[..., None]
        col = col * (1 - b) + c * b
    relief = noise(7, 3, 1.0) + noise(8, 9, 1.4)
    col += relief[..., None] * 10
    col = col * (1 - 0.18 * np.clip(noise(9, 14, 1.0), 0, 1))[..., None] + rock * 0.18 * np.clip(noise(9, 14, 1.0), 0, 1)[..., None]

    ice = np.clip((np.abs(lat) - 62) / 12, 0, 1) ** 1.5
    gl = np.asarray(mask_from([LAND["greenland"]]), np.float32) / 255
    ice = np.maximum(ice, gl * 0.95)
    ice = np.maximum(ice, np.asarray(mask_from([LAND["antarctica"]]), np.float32) / 255)
    ice_col = np.array([238, 244, 250], np.float32)
    col = col * (1 - ice[..., None]) + ice_col * ice[..., None]

    # sea ice around the poles
    sea_ice = np.clip((np.abs(lat) - 76) / 14, 0, 1) ** 1.3 * (1 - land)
    ocean = ocean * (1 - sea_ice[..., None] * 0.85) + ice_col * sea_ice[..., None] * 0.85

    rgb = ocean * (1 - land[..., None]) + col * land[..., None]
    # soft white cloud wisps
    cl = np.clip(noise(21, 30, 1.0) + noise(22, 12, 0.4) - 0.35, 0, 1)
    rgb = rgb * (1 - 0.22 * cl[..., None]) + 255 * 0.22 * cl[..., None]
    Image.fromarray(np.clip(rgb, 0, 255).astype(np.uint8)).save(OUT, quality=88, optimize=True)
    print("wrote", OUT)

if __name__ == "__main__":
    main()
